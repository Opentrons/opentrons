#!/usr/bin/env node
'use strict'

/**
 * Cypress Cache Automation Script
 * 
 * This script automates the process of caching Cypress binaries in GitHub releases.
 * When a Cypress version is not found in GitHub releases, it downloads the binary
 * from the official source and uploads it to a GitHub release for future use.
 * 
 * Usage: node scripts/cypress-cache-automation.js [--deploy]
 * --deploy: Actually create the release and upload assets (default: dry run)
 */

const { Octokit } = require('@octokit/rest')
const fs = require('fs')
const path = require('path')
const https = require('https')
const { execSync } = require('child_process')

const REPO_DETAILS = {
  owner: 'Opentrons',
  repo: 'cypress-mirror',
}

const PLATFORMS = [
  { os: 'Linux', platform: 'linux', arch: 'x64' },
  { os: 'macOS', platform: 'darwin', arch: 'x64' },
  { os: 'Windows', platform: 'win32', arch: 'x64' }
]

async function getCypressVersion() {
  try {
    const packageJson = JSON.parse(fs.readFileSync('package.json', 'utf8'))
    return packageJson.dependencies?.cypress || packageJson.devDependencies?.cypress
  } catch (error) {
    console.error('Error reading package.json:', error.message)
    process.exit(1)
  }
}

async function checkReleaseExists(octokit, version) {
  try {
    const { data } = await octokit.rest.repos.getReleaseByTag({
      owner: REPO_DETAILS.owner,
      repo: REPO_DETAILS.repo,
      tag: `cypress-${version}`
    })
    return { exists: true, release: data }
  } catch (error) {
    if (error.status === 404) {
      return { exists: false, release: null }
    }
    throw error
  }
}

async function downloadFile(url, filepath) {
  return new Promise((resolve, reject) => {
    const file = fs.createWriteStream(filepath)
    https.get(url, (response) => {
      if (response.statusCode !== 200) {
        reject(new Error(`Failed to download: ${response.statusCode}`))
        return
      }
      response.pipe(file)
      file.on('finish', () => {
        file.close()
        resolve()
      })
    }).on('error', (err) => {
      fs.unlink(filepath, () => {}) // Delete the file on error
      reject(err)
    })
  })
}

async function downloadCypressBinary(version, platform, arch) {
  const url = `https://download.cypress.io/desktop/${version}?platform=${platform}&arch=${arch}`
  const filename = `cypress-${version}-${platform}-${arch}.zip`
  const filepath = path.join(__dirname, '..', 'temp', filename)
  
  // Create temp directory if it doesn't exist
  const tempDir = path.dirname(filepath)
  if (!fs.existsSync(tempDir)) {
    fs.mkdirSync(tempDir, { recursive: true })
  }
  
  console.log(`Downloading ${filename} from ${url}`)
  await downloadFile(url, filepath)
  console.log(`Downloaded ${filename}`)
  
  return { filepath, filename }
}

async function createRelease(octokit, version, deploy) {
  const tagName = `cypress-${version}`
  const releaseName = `Cypress ${version} Cache`
  const body = `Cached Cypress ${version} binaries for faster CI builds.

This release contains pre-downloaded Cypress binaries for all supported platforms to speed up CI builds.

**Generated by:** Cypress Cache Automation Script
**Cypress Version:** ${version}
**Created:** ${new Date().toISOString()}`

  if (deploy) {
    const { data } = await octokit.rest.repos.createRelease({
      owner: REPO_DETAILS.owner,
      repo: REPO_DETAILS.repo,
      tag_name: tagName,
      name: releaseName,
      body: body,
      draft: false,
      prerelease: false
    })
    return data
  } else {
    console.log(`[DRY RUN] Would create release: ${tagName}`)
    console.log(`[DRY RUN] Title: ${releaseName}`)
    console.log(`[DRY RUN] Body: ${body}`)
    return { id: 'dry-run', upload_url: 'dry-run' }
  }
}

async function uploadAsset(octokit, release, filepath, filename, deploy) {
  if (!deploy) {
    console.log(`[DRY RUN] Would upload asset: ${filename}`)
    return
  }

  const fileContent = fs.readFileSync(filepath)
  const { data } = await octokit.rest.repos.uploadReleaseAsset({
    owner: REPO_DETAILS.owner,
    repo: REPO_DETAILS.repo,
    release_id: release.id,
    name: filename,
    data: fileContent,
    headers: {
      'content-type': 'application/zip',
      'content-length': fileContent.length
    }
  })
  console.log(`Uploaded ${filename}`)
  return data
}

async function cleanup(filepaths) {
  for (const filepath of filepaths) {
    try {
      fs.unlinkSync(filepath)
      console.log(`Cleaned up ${filepath}`)
    } catch (error) {
      console.warn(`Failed to cleanup ${filepath}:`, error.message)
    }
  }
  
  // Remove temp directory if empty
  const tempDir = path.join(__dirname, '..', 'temp')
  try {
    fs.rmdirSync(tempDir)
    console.log(`Cleaned up temp directory`)
  } catch (error) {
    // Directory not empty or doesn't exist, that's fine
  }
}

async function main() {
  const deploy = process.argv.includes('--deploy')
  const token = process.env.GITHUB_TOKEN
  
  if (!token) {
    console.error('GITHUB_TOKEN environment variable is required')
    process.exit(1)
  }

  const octokit = new Octokit({ auth: token })
  const cypressVersion = await getCypressVersion()
  
  console.log(`Cypress version: ${cypressVersion}`)
  
  // Check if release already exists
  const { exists, release } = await checkReleaseExists(octokit, cypressVersion)
  
  if (exists) {
    console.log(`Release cypress-${cypressVersion} already exists`)
    console.log(`Release URL: ${release.html_url}`)
    return
  }
  
  console.log(`Release cypress-${cypressVersion} does not exist. Creating...`)
  
  // Create the release
  const newRelease = await createRelease(octokit, cypressVersion, deploy)
  
  if (deploy) {
    console.log(`Created release: ${newRelease.html_url}`)
  }
  
  // Download and upload binaries for all platforms
  const downloadedFiles = []
  
  try {
    for (const { os, platform, arch } of PLATFORMS) {
      console.log(`\nProcessing ${os} (${platform}-${arch})...`)
      
      const { filepath, filename } = await downloadCypressBinary(cypressVersion, platform, arch)
      downloadedFiles.push(filepath)
      
      await uploadAsset(octokit, newRelease, filepath, filename, deploy)
    }
    
    console.log(`\n✅ Successfully cached Cypress ${cypressVersion} for all platforms`)
    if (deploy) {
      console.log(`Release URL: ${newRelease.html_url}`)
    }
    
  } finally {
    // Cleanup downloaded files
    await cleanup(downloadedFiles)
  }
}

if (require.main === module) {
  main().catch((error) => {
    console.error('Error:', error.message)
    process.exit(1)
  })
}

module.exports = { main }
