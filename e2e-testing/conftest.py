"""Pytest configuration for Playwright e2e tests.

This module configures test reporting and artifacts:
- Videos: Recorded for all tests (pass/fail) to test-results/videos/
- Screenshots: Captured on test failure to test-results/screenshots/
- HTML Report: Generated by pytest-html to test-results/report.html
- Server Management: Auto-starts/reuses Protocol Designer for local tests
"""

import os
import select
import subprocess
import time
import urllib.request
from collections.abc import Generator
from typing import Any

import pytest
from playwright.sync_api import Page

try:
    from pytest_html import extras as pytest_html_extras  # type: ignore[import-untyped]
except ImportError:
    pytest_html_extras = None


def pytest_configure(config: Any) -> None:
    """Create test-results directory if it doesn't exist.

    This runs before any tests and ensures the directory exists for
    pytest-html to write the report.
    """
    os.makedirs("test-results", exist_ok=True)


