@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_makereport(item: Any, call: Any) -> Any:
    """Hook to capture screenshots on test failure.

    Screenshots are saved to test-results/screenshots/ with the test name.
    """
    outcome = yield
    rep = outcome.get_result()

    # Initialize extra list for pytest-html
    if pytest_html_extras:
        extra = getattr(rep, "extra", [])
        rep.extra = extra

        # Capture screenshot on test failure (during call phase)
        if rep.when == "call" and rep.failed:
            page = item.funcargs.get("page")
            if page:
                screenshot_dir = "test-results/screenshots"
                os.makedirs(screenshot_dir, exist_ok=True)
                screenshot_path = os.path.join(
                    screenshot_dir, f"{item.nodeid.replace('::', '_').replace('/', '_')}.png"
                )
                try:
                    page.screenshot(path=screenshot_path, full_page=True)
                    print(f"\n📸 Screenshot saved: {screenshot_path}")
                    rep.extra.append(pytest_html_extras.image(screenshot_path, name="Screenshot on Failure"))
                except Exception as e:
                    print(f"\n⚠️  Failed to capture screenshot: {e}")


@pytest.hookimpl(tryfirst=True)
def pytest_runtest_teardown(item: Any) -> None:
    """Hook to save video path for post-processing.

    Stores the video path on the item so we can inject it into the HTML report
    during the session finish hook.
    """
    try:
        page = item.funcargs.get("page")
        if page and page.video:
            video = page.video
            # Get the path - this triggers waiting for video to be saved
            try:
                video_path = video.path()
                # Store on config for later access in terminal_summary
                if not hasattr(item.config, "_test_videos"):
                    item.config._test_videos = {}
                item.config._test_videos[item.nodeid] = video_path
                print(f"\n🎥 Video saved: {video_path}")
            except Exception as e:
                print(f"\n⚠️  Could not get video path: {e}")
    except Exception:
        pass


def pytest_terminal_summary(terminalreporter: Any) -> None:
    """Post-process HTML report to inject video elements.

    This hook runs after all tests complete and reports are generated.
    We inject video elements into the HTML by modifying the JSON data structure.
    """
    # Only process if we have videos and HTML report was generated
    html_path = "test-results/report.html"
    if not os.path.exists(html_path):
        return

    test_videos = getattr(terminalreporter.config, "_test_videos", {})
    if not test_videos:
        return

    print(f"\n🎬 Post-processing HTML report to add {len(test_videos)} video(s)...")

    try:
        # Read the HTML file
        with open(html_path, encoding="utf-8") as f:
            html_content = f.read()

        # Find and parse the JSON data blob
        import json
        import re

        # Extract the JSON blob from the HTML
        match = re.search(r'data-jsonblob="([^"]+)"', html_content)
        if not match:
            print("⚠️  Could not find JSON blob in HTML report")
            return

        # Decode HTML entities
        json_str = match.group(1).replace("&#34;", '"')
        data = json.loads(json_str)

        # Inject video HTML into each test's extras
        for test_id, video_path in test_videos.items():
            if test_id in data.get("tests", {}):
                rel_video_path = os.path.relpath(video_path, "test-results")
                video_html = (
                    '<div style="margin: 10px 0;">'
                    "<details open><summary>📹 Test Recording</summary>"
                    f'<video width="100%" style="max-width: 800px;" controls>'
                    f'<source src="{rel_video_path}" type="video/webm">'
                    "Your browser does not support the video tag."
                    "</video></details></div>"
                )

                # Add to extras array
                for test_result in data["tests"][test_id]:
                    test_result.setdefault("extras", []).append(
                        {"name": "Video", "format_type": "html", "content": video_html}
                    )

        # Re-encode the JSON and inject back into HTML
        new_json_str = json.dumps(data, separators=(",", ": "))
        new_json_encoded = new_json_str.replace('"', "&#34;")
        html_content = html_content.replace(match.group(1), new_json_encoded)

        # Write the modified HTML
        with open(html_path, "w", encoding="utf-8") as f:
            f.write(html_content)

        print(f"✅ Successfully added {len(test_videos)} video(s) to HTML report\n")

    except Exception as e:
        print(f"⚠️  Failed to post-process HTML report: {e}\n")
