@pytest.fixture(scope="session")
def base_url() -> str:
    """Get base URL from environment or detect running local server.

    For local testing, automatically detects if server is running on ports 4173-4175.
    """
    env = os.environ.get("TEST_ENV", "local")
    environments = {
        "staging": "https://staging.designer.opentrons.com",
        "prod": "https://designer.opentrons.com",
    }

    if env != "local":
        return environments.get(env, "http://localhost:4173")

    # For local testing, check if server is already running on any port
    running_server = _find_running_server()
    if running_server:
        return running_server

    # Default to 4173 if no server found yet (will be started by dev_server fixture)
    return "http://localhost:4173"


def _is_server_running(url: str, timeout: int = 1) -> bool:
    """Check if server is already running at the given URL."""
    try:
        urllib.request.urlopen(url, timeout=timeout)
        return True
    except Exception:
        return False


def _find_running_server() -> str | None:
    """Find if Protocol Designer server is running on any common port."""
    ports_to_check = [4173, 4174, 4175]
    for port in ports_to_check:
        url = f"http://localhost:{port}"
        if _is_server_running(url):
            return url
    return None


@pytest.fixture(scope="session", autouse=True)
def dev_server(base_url: str) -> Generator[subprocess.Popen[str] | None, None, None]:
    """Start local production preview server if testing against localhost.

    If the server is already running on any port (4173, 4174, 4175), it will be reused
    instead of starting a new one. The test will use whichever port the server is on.

    Set SKIP_SERVER_START=true to always skip starting the server (useful for background processes).
    """
    if "localhost" in base_url:
        # Check if we should skip server management entirely
        skip_server = os.environ.get("SKIP_SERVER_START", "false").lower() == "true"

        # Check if server is already running on any port
        existing_server = _find_running_server()
        if existing_server:
            print(f"\n✓ Server already running on {existing_server}, skipping startup")
            # Update base_url if server is on different port
            if existing_server != base_url:
                print(f"  (Note: Using {existing_server} instead of {base_url})")
            yield None
            return

        if skip_server:
            raise Exception(
                "SKIP_SERVER_START is set but server is not running on any port (4173-4175). "
                "Please start the server manually with: cd protocol-designer && make serve"
            )

        print(f"\nStarting protocol-designer preview server on {base_url}...")

        # Start the preview server (vite preview serves production build)
        process = subprocess.Popen(
            ["make", "-C", "../protocol-designer", "serve"],
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,  # Combine stderr into stdout to capture port messages
            text=True,
        )

        # Wait for server to be ready, checking both common ports
        max_attempts = 60
        ports_to_try = [4173, 4174, 4175]  # vite preview will try these in order
        server_ready = False

        for attempt in range(max_attempts):
            # Check if process has output about the port
            if process.stdout and select.select([process.stdout], [], [], 0.1)[0]:
                line = process.stdout.readline()
                if "Local:" in line:
                    print(f"Server output: {line.strip()}")

            # Try to connect to possible ports
            for port in ports_to_try:
                try:
                    test_url = f"http://localhost:{port}"
                    urllib.request.urlopen(test_url, timeout=1)
                    print(f"Preview server is ready on {test_url}")
                    server_ready = True
                    break
                except Exception:
                    pass

            if server_ready:
                break

            if attempt == max_attempts - 1:
                process.kill()
                raise Exception(f"Preview server failed to start on any port: {ports_to_try}")
            time.sleep(2)

        yield process

        # Cleanup - only kill if we started it
        print("\nStopping dev server...")
        process.terminate()
        try:
            process.wait(timeout=5)
        except subprocess.TimeoutExpired:
            process.kill()
    else:
        # Not using local server
        yield None


